# Lesson 2 — Types & Variables
# File: lesson02_types_and_variables.py


# 1) Integers and floats
i = 42
f = 3.14
print(type(i), type(f))

# 2) Strings
s = "Python"
print(s, len(s))

# 3) Booleans
b = True
print(b, type(b))

# 4) None
n = None
print(n is None)

# 5) Type casting
num = "123"
num_int = int(num)
print(num_int + 1)
