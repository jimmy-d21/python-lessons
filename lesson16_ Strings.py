# create string
text = "Python"
print(text)

# get character by index
print(text[0])

# get length of string
print(len(text))

# convert to uppercase
print(text.upper())

# convert to lowercase
print(text.lower())

# replace text
print(text.replace("Py", "My"))

# check if substring exists
print("on" in text)

# split string
sentence = "I love Python"
print(sentence.split())
